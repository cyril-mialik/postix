CREATE TABLE report_status (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) UNIQUE NOT NULL,
    description TEXT,

    CONSTRAINT chk_valid_report_status CHECK (name IN ('pending', 'resolved_dismissed', 'resolved_actioned'))
);

