CREATE TABLE post_review_rating (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    review_id INT NOT NULL,
    profile_id UUID NOT NULL,

    CONSTRAINT fk_post_review_rating_review
        FOREIGN KEY (review_id) REFERENCES post_review(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_post_review_rating_profile
        FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT chk_post_review_rating_valid CHECK (rating >= 1 AND rating <= 5),
    CONSTRAINT uq_post_review_rating UNIQUE (review_id, profile_id)
);

CREATE INDEX idx_post_review_rating_profile ON post_review_rating (profile_id);
