CREATE TABLE post_review (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review TEXT NOT NULL,

    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now(),

    post_id UUID NOT NULL,
    profile_id UUID NOT NULL,
    
    CONSTRAINT fk_post_review_post FOREIGN KEY (post_id) REFERENCES post(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_profile_review_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX idx_post_review_post ON post_review (post_id);
CREATE INDEX idx_post_review_profile ON post_review (profile_id);
