CREATE TABLE post_status (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) UNIQUE NOT NULL,
    description TEXT,

    CONSTRAINT chk_valid_post_status CHECK (name IN ('draft', 'published', 'archived', 'deleted'))
);

