CREATE TABLE post_rating (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating INT NOT NULL,

    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now(),

    post_id UUID NOT NULL,
    profile_id UUID NOT NULL,
    
    CONSTRAINT fk_post_rating_post FOREIGN KEY (post_id) REFERENCES post(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_profile_rating_profile FOREIGN KEY (profile_id) REFERENCES profile(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT chk_valid_rating CHECK (rating >= 1 AND rating <= 5)
);

CREATE UNIQUE INDEX uq_post_rating ON post_rating (post_id, profile_id);
CREATE INDEX idx_post_rating_profile ON post_rating (profile_id);
CREATE INDEX idx_post_rating_post ON post_rating (post_id);
